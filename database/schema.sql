-- ── 5. Creación de Tablas ───────────────────────────────────────────

-- 5.1 Tabla USUARIO
CREATE TABLE USUARIO (
    ID_USUARIO   NUMBER(10) PRIMARY KEY,
    NOMBRE       VARCHAR2(100) NOT NULL,
    APELLIDO     VARCHAR2(100),
    EMAIL        VARCHAR2(150) UNIQUE NOT NULL,
    CONTRASENA   VARCHAR2(255) NOT NULL,
    ROL          VARCHAR2(30) NOT NULL CHECK (ROL IN ('DIRECTOR', 'COORDINADOR', 'ESTUDIANTE', 'TUTOR', 'ASESOR')),
    ACTIVO       VARCHAR2(10) DEFAULT 'S' CHECK (ACTIVO IN ('S', 'N'))
);

-- 5.2 Tabla MODALIDAD (Modalidades pedagógicas curriculares)
CREATE TABLE MODALIDAD (
    ID_MODALIDAD   NUMBER(10) PRIMARY KEY,
    NOMBRE         VARCHAR2(100) NOT NULL,
    DESCRIPCION    VARCHAR2(500),
    HORAS_DEFAULT  NUMBER(4) DEFAULT 64,
    ESTADO         VARCHAR2(10) DEFAULT 'ACTIVO' CHECK (ESTADO IN ('ACTIVO', 'INACTIVO'))
);

-- 5.3 Tabla INSTITUCION (Centros educativos y convenios de práctica)
CREATE TABLE INSTITUCION (
    ID_INSTITUCION       NUMBER(10) PRIMARY KEY,
    NOMBRE               VARCHAR2(200) NOT NULL,
    DIRECCION            VARCHAR2(250),
    TELEFONO             VARCHAR2(50),
    CONVENIO_ACTIVO      VARCHAR2(10) DEFAULT 'S' CHECK (CONVENIO_ACTIVO IN ('S', 'N')),
    CUPOS_DISPONIBLES    NUMBER(4) DEFAULT 5,
    FECHA_VENC_CONVENIO  DATE
);

-- 5.4 Tabla PRACTICA (Prácticas académicas semestrales)
CREATE TABLE PRACTICA (
    ID_PRACTICA      NUMBER(10) PRIMARY KEY,
    NOMBRE           VARCHAR2(150) NOT NULL,
    SEMESTRE         NUMBER(2) DEFAULT 1,
    TIPO             VARCHAR2(30) DEFAULT 'OBSERVACION',
    ID_MODALIDAD     NUMBER(10),
    HORAS_REQUERIDAS NUMBER(4) DEFAULT 64,
    ESTADO           VARCHAR2(20) DEFAULT 'ABIERTA' CHECK (ESTADO IN ('ABIERTA', 'CERRADA')),
    DESCRIPCION      VARCHAR2(500),
    CONSTRAINT FK_PRAC_MODALIDAD FOREIGN KEY (ID_MODALIDAD) REFERENCES MODALIDAD(ID_MODALIDAD)
);

-- 5.5 Tabla ASIGNACION (Vinculación formal Estudiante - Práctica - Institución - Tutor)
CREATE TABLE ASIGNACION (
    ID_ASIGNACION      NUMBER(10) PRIMARY KEY,
    ID_USUARIO         NUMBER(10),
    ID_ESTUDIANTE      NUMBER(10),
    ID_TUTOR           NUMBER(10),
    ID_PRACTICA        NUMBER(10) NOT NULL,
    ID_INSTITUCION     NUMBER(10),
    HORAS_ACUMULADAS   NUMBER(6,2) DEFAULT 0,
    ESTADO             VARCHAR2(20) DEFAULT 'APROBADA',
    ESTADO_APROBACION  VARCHAR2(20) DEFAULT 'APROBADA' CHECK (ESTADO_APROBACION IN ('PENDIENTE', 'APROBADA', 'RECHAZADA')),
    ESTADO_PRACTICA    VARCHAR2(20) DEFAULT 'EN_CURSO',
    FECHA_ASIGNACION   DATE,
    CONSTRAINT FK_ASIG_ESTUDIANTE  FOREIGN KEY (ID_ESTUDIANTE)  REFERENCES USUARIO(ID_USUARIO),
    CONSTRAINT FK_ASIG_TUTOR       FOREIGN KEY (ID_TUTOR)       REFERENCES USUARIO(ID_USUARIO),
    CONSTRAINT FK_ASIG_PRACTICA    FOREIGN KEY (ID_PRACTICA)    REFERENCES PRACTICA(ID_PRACTICA),
    CONSTRAINT FK_ASIG_INSTITUCION FOREIGN KEY (ID_INSTITUCION) REFERENCES INSTITUCION(ID_INSTITUCION)
);

-- 5.6 Tabla BITACORA (Registro estructurado de sesiones y momentos pedagógicos)
CREATE TABLE BITACORA (
    ID_BITACORA     NUMBER(10) PRIMARY KEY,
    ID_ASIGNACION   NUMBER(10) NOT NULL,
    NUMERO_VISITA   NUMBER(4) NOT NULL,
    FECHA_REGISTRO  DATE NOT NULL,
    HORAS_SESION    NUMBER(5,2) DEFAULT 16,
    ACTIVIDADES     VARCHAR2(4000) NOT NULL,
    OBSERVACIONES   VARCHAR2(4000),
    URL_EVIDENCIA   VARCHAR2(500),
    ESTADO_REVISION VARCHAR2(20) DEFAULT 'PENDIENTE',
    CONSTRAINT FK_BITACORA_ASIG FOREIGN KEY (ID_ASIGNACION) REFERENCES ASIGNACION(ID_ASIGNACION)
);

-- 5.7 Tabla VISITA (Planificación y seguimiento de visitas docentes de campo)
CREATE TABLE VISITA (
    ID_VISITA         NUMBER(10) PRIMARY KEY,
    ID_ASIGNACION     NUMBER(10),
    ID_PRACTICA       NUMBER(10),
    NUMERO_VISITA     NUMBER(4) NOT NULL,
    FECHA_PROGRAMADA  DATE,
    FECHA_REALIZADA   DATE,
    ESTADO            VARCHAR2(20) DEFAULT 'PROGRAMADA' CHECK (ESTADO IN ('PROGRAMADA', 'REALIZADA', 'CANCELADA')),
    TIPO_VISITA       VARCHAR2(30) DEFAULT 'SEGUIMIENTO',
    OBSERVACIONES     VARCHAR2(1000),
    CONSTRAINT FK_VISITA_ASIG FOREIGN KEY (ID_ASIGNACION) REFERENCES ASIGNACION(ID_ASIGNACION),
    CONSTRAINT FK_VISITA_PRAC FOREIGN KEY (ID_PRACTICA)   REFERENCES PRACTICA(ID_PRACTICA)
);

-- 5.8 Tabla EVALUACION (Rúbrica y calificaciones cuantitativas formativas)
CREATE TABLE EVALUACION (
    ID_EVALUACION    NUMBER(10) PRIMARY KEY,
    ID_BITACORA      NUMBER(10) NOT NULL,
    ID_EVALUADOR     NUMBER(10) NOT NULL,
    TIPO_EVALUADOR   VARCHAR2(20) NOT NULL CHECK (TIPO_EVALUADOR IN ('TUTOR', 'ASESOR')),
    NOTA             NUMBER(4,2) NOT NULL,
    COMENTARIOS      VARCHAR2(1000),
    FECHA_EVALUACION DATE,
    CONSTRAINT FK_EVAL_BITACORA  FOREIGN KEY (ID_BITACORA)  REFERENCES BITACORA(ID_BITACORA),
    CONSTRAINT FK_EVAL_EVALUADOR FOREIGN KEY (ID_EVALUADOR) REFERENCES USUARIO(ID_USUARIO)
);

-- 5.9 Tabla EVIDENCIA (Portafolio digital de evidencias de aprendizaje)
CREATE TABLE EVIDENCIA (
    ID_EVIDENCIA    NUMBER(10) PRIMARY KEY,
    ID_BITACORA     NUMBER(10),
    NUMERO_VISITA   NUMBER(4) DEFAULT 1,
    NOMBRE_ARCHIVO  VARCHAR2(255),
    RUTA_ARCHIVO    VARCHAR2(500) NOT NULL,
    TIPO_FORMATO    VARCHAR2(50) DEFAULT 'PDF',
    FECHA_CARGA     DATE,
    CONSTRAINT FK_EVID_BITACORA FOREIGN KEY (ID_BITACORA) REFERENCES BITACORA(ID_BITACORA)
);

-- 5.10 Tabla PREGUNTA (Banco de preguntas de reflexión pedagógica por visita)
CREATE TABLE PREGUNTA (
    ID_PREGUNTA     NUMBER(10) PRIMARY KEY,
    ID_PRACTICA     NUMBER(10) DEFAULT 1,
    NUMERO_VISITA   NUMBER(4) DEFAULT 1,
    TEXTO_PREGUNTA  VARCHAR2(500) NOT NULL,
    CATEGORIA       VARCHAR2(100) DEFAULT 'PEDAGOGICA',
    ORDEN           NUMBER(4) DEFAULT 1,
    CONSTRAINT FK_PREG_PRACTICA FOREIGN KEY (ID_PRACTICA) REFERENCES PRACTICA(ID_PRACTICA)
);

-- 5.11 Tabla PREGUNTA_GUIA (Guía pedagógica parametrizable por práctica y modalidad)
CREATE TABLE PREGUNTA_GUIA (
    ID_PREGUNTA      NUMBER(10) PRIMARY KEY,
    ID_PREGUNTA_GUIA NUMBER(10),
    ID_PRACTICA      NUMBER(10) DEFAULT 1,
    ID_MODALIDAD     NUMBER(10),
    NUMERO_VISITA    NUMBER(4) DEFAULT 1,
    TEXTO_PREGUNTA   VARCHAR2(500) NOT NULL,
    CATEGORIA        VARCHAR2(100) DEFAULT 'PEDAGOGICA',
    ORDEN            NUMBER(4) DEFAULT 1,
    CONSTRAINT FK_PG_PRACTICA  FOREIGN KEY (ID_PRACTICA)  REFERENCES PRACTICA(ID_PRACTICA),
    CONSTRAINT FK_PG_MODALIDAD FOREIGN KEY (ID_MODALIDAD) REFERENCES MODALIDAD(ID_MODALIDAD)
);

